import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy import stats

def compare_intervals(n, distribution, num_simulations=1000,
                      num_bootstrap=1000, seed=42):

    rng = np.random.default_rng(seed)

    t_coverage = 0
    boot_coverage = 0
    t_widths = []
    boot_widths = []

    for i in range(num_simulations):

        # Generate sample
        if distribution == "normal":
            sample = rng.normal(100, 15, size=n)
        elif distribution == "moderate":
            sample = rng.gamma(4, 7.5, size=n) + 70
        elif distribution == "strong":
            sample = rng.exponential(15, size=n) + 85
        else:
            raise ValueError("Unknown distribution")

        # Conventional t interval
        mean = np.mean(sample)
        sd = np.std(sample, ddof=1)
        se = sd / np.sqrt(n)

        tcrit = stats.t.ppf(0.975, df=n-1)
        t_lower = mean - tcrit * se
        t_upper = mean + tcrit * se

        # Percentile bootstrap interval
        boot_samples = rng.choice(
            sample, size=(num_bootstrap, n), replace=True
        )
        boot_means = np.mean(boot_samples, axis=1)
        b_lower, b_upper = np.percentile(
            boot_means, [2.5, 97.5]
        )

        # Record coverage
        t_coverage += (t_lower <= 100 <= t_upper)
        boot_coverage += (b_lower <= 100 <= b_upper)

        # Record widths
        t_widths.append(t_upper - t_lower)
        boot_widths.append(b_upper - b_lower)

    return {
        "distribution": distribution,
        "n": n,
        "t_coverage": t_coverage / num_simulations * 100,
        "bootstrap_coverage": boot_coverage / num_simulations * 100,
        "t_width": np.mean(t_widths),
        "bootstrap_width": np.mean(boot_widths)
    }

def main():

    final_results = []

    distributions = ["normal", "moderate", "strong"]
    sample_sizes = [10, 30, 100, 500]

    for i, distribution in enumerate(distributions):
        for j, n in enumerate(sample_sizes):
            result = compare_intervals(
                n,
                distribution,
                num_simulations=1000,
                num_bootstrap=1000,
                seed=42 + i * 100 + j
            )
            final_results.append(result)

    final_df = pd.DataFrame(final_results)

    results_df = final_df.copy()

    print(final_df.round(2).to_string(index=False))

    """## Simulation Results

    The following figures summarize empirical confidence interval coverage across sample sizes and population distributions.

    **Figure 1** shows the coverage achieved by conventional Student's t intervals relative to the nominal 95% confidence level.

    **Figure 2** presents the corresponding coverage rates for percentile bootstrap intervals.

    **Figure 3** displays the difference in empirical coverage between the two methods (bootstrap minus t). Negative values indicate that the percentile bootstrap achieved lower coverage.

    Because each condition was evaluated using 1,000 Monte Carlo replications, small differences should be interpreted cautiously.
    """

    plt.figure(figsize=(9, 6))

    for distribution in ["normal", "moderate", "strong"]:
        data = results_df[
            results_df["distribution"] == distribution
        ]

        plt.plot(
            data["n"],
            data["t_coverage"],
            marker="o",
            linewidth=2,
            label=distribution.capitalize()
        )

    # Reference line for nominal coverage
    plt.axhline(
        y=95,
        color="black",
        linestyle="--",
        label="Nominal 95% coverage"
    )

    plt.xscale("log")
    plt.xlabel("Sample Size (n)")
    plt.ylabel("Empirical Coverage (%)")
    plt.title("Figure 1: Confidence Interval Coverage Across Sample Sizes")
    plt.legend()
    plt.grid(alpha=0.3)
    plt.tight_layout()

    plt.savefig("coverage_by_sample_size.png", dpi=300)
    plt.show()

    plt.figure(figsize=(9, 6))

    for distribution in ["normal", "moderate", "strong"]:
        data = results_df[
            results_df["distribution"] == distribution
        ]

        plt.plot(
            data["n"],
            data["bootstrap_coverage"],
            marker="o",
            linewidth=2,
            label=distribution.capitalize()
        )

    plt.axhline(
        y=95,
        color="black",
        linestyle="--",
        label="Nominal 95% coverage"
    )

    plt.xscale("log")
    plt.xlabel("Sample Size (n)")
    plt.ylabel("Empirical Coverage (%)")
    plt.title("Figure 2: Bootstrap Confidence Interval Coverage Across Sample Sizes")
    plt.legend()
    plt.grid(alpha=0.3)
    plt.tight_layout()

    plt.savefig("bootstrap_coverage.png", dpi=300)
    plt.show()

    results_df["coverage_difference"] = (
        results_df["bootstrap_coverage"]
        - results_df["t_coverage"]
    )

    plt.figure(figsize=(9, 6))

    for distribution in ["normal", "moderate", "strong"]:
        data = results_df[
            results_df["distribution"] == distribution
        ]

        plt.plot(
            data["n"],
            data["coverage_difference"],
            marker="o",
            linewidth=2,
            label=distribution.capitalize()
        )

    plt.axhline(0, color="black", linestyle="--")

    plt.xscale("log")
    plt.xlabel("Sample Size (n)")
    plt.ylabel("Bootstrap Minus t Coverage (percentage points)")
    plt.title("Figure 3: Coverage Difference Between Confidence Interval Methods")
    plt.legend()
    plt.grid(alpha=0.3)
    plt.tight_layout()

    plt.savefig("coverage_difference.png", dpi=300)
    plt.show()

    num_simulations = 1000

    for method in ["t", "bootstrap"]:
        coverage = results_df[f"{method}_coverage"] / 100

        results_df[f"{method}_mcse"] = (
            np.sqrt(coverage * (1 - coverage) / num_simulations)
            * 100
        )

    print(
        results_df[
        ["distribution", "n", "t_coverage",
        "t_mcse", "bootstrap_coverage", "bootstrap_mcse"]
        ].round(2).to_string(index=False)
    )

    results_df.to_csv(
        "final_confidence_interval_results.csv",
        index=False
    )

    print("Final results updated with Monte Carlo standard errors.")
    print("Total conditions:", len(results_df))

    # Final research validation checks

    assert len(results_df) == 12, "Expected 12 experimental conditions"

    assert set(results_df["distribution"]) == {
        "normal", "moderate", "strong"
    }

    assert set(results_df["n"]) == {10, 30, 100, 500}

    assert results_df["t_coverage"].between(0, 100).all()
    assert results_df["bootstrap_coverage"].between(0, 100).all()

    assert (results_df["t_width"] > 0).all()
    assert (results_df["bootstrap_width"] > 0).all()

    assert results_df[
        ["distribution", "n"]
    ].duplicated().sum() == 0

